#!/bin/bash

if [[ "$OSTYPE" =~ ^darwin ]]; then
  DEFAULT_PATH="~/SimplicityStudio/SDKs/gsdk_4_4_1"
elif [ -f /.dockerenv ]; then
  DEFAULT_PATH="/gecko_sdk/"
else
  DEFAULT_PATH=
fi

# BG_EXTRA_DEFS (for example -DBG_DIAG, the diagnostic build) is added to the compiler defines, BG_OUT names the output image
GIT_VERSION="$(git describe --abbrev=4 --dirty --always --tags --all --match releases/*)"

GSDK_PATH=${GSDK_PATH:=$DEFAULT_PATH}

rm -rf ./out
slc generate -s ${GSDK_PATH} -p BG22Badge.slcp -o makefile -d ./out -cp
echo "--- gatt files after slc generate:"; find out -name 'gatt_db*'
if [ ! -f out/autogen/gatt_db.h ]; then
  echo "--- gatt_db was not generated by slc, running bgbuild.py by hand"
  python3 ${GSDK_PATH}/protocol/bluetooth/bin/gatt/bgbuild.py config/btconf -o out/autogen || { echo "bgbuild failed"; exit 1; }
  ls -la out/autogen | grep gatt
fi
# if the generated makefile does not build gatt_db.c, ble_badge.c includes it when this marker exists
if ! grep -q 'gatt_db\.c' out/BG22Badge.project.mak; then
  echo "--- gatt_db.c is not in the makefile: using the include marker"
  touch out/autogen/bg22_gattdb_inline.h
fi
echo "--- makefile lines with gatt_db / sl_event_handler:"; grep -n "gatt_db\|sl_event_handler" out/BG22Badge.project.mak | head
cd out

# For some reason, the autogenerated makefile insists on not allowing C define
# overrides. So patch it before running make.
if [[ "$OSTYPE" =~ ^darwin ]]; then
sed -i '' 's/C_DEFS   =/C_DEFS ?=/' BG22Badge.Makefile
else
sed -i 's/C_DEFS   =/C_DEFS ?=/' BG22Badge.Makefile
fi

# The SDK insists on using LFXO, even though some of the tags don't have
# it. Patch the autogenerated file to fall back on LFRCO.
if [[ "$OSTYPE" =~ ^darwin ]]; then
  sed -i '' 's/, LFXO/, LFRCO/' autogen/sl_device_init_clocks.c
  sed -i '' 's/ sl_device_init_lfxo/\/\/ sl_device_init_lfxo/' autogen/sl_event_handler.c
else
  sed -i 's/, LFXO/, LFRCO/' autogen/sl_device_init_clocks.c
  sed -i 's/ sl_device_init_lfxo/\/\/ sl_device_init_lfxo/' autogen/sl_event_handler.c
fi

# The debug USART defaults to blocking sleep to enable RX. Since we're not relying
# on RX, turn it off.
# Note: this is probably a bug in the project generator, as this is already attempting
# to be set in the .slcp, but somehow it doesn't take effect.
if [[ "$OSTYPE" =~ ^darwin ]]; then
  sed -i '' 's/SL_IOSTREAM_EUSART_EUART_DEBUG_RESTRICT_ENERGY_MODE_TO_ALLOW_RECEPTION    1/SL_IOSTREAM_EUSART_EUART_DEBUG_RESTRICT_ENERGY_MODE_TO_ALLOW_RECEPTION    0/' config/sl_iostream_eusart_euart_debug_config.h
else
  sed -i 's/SL_IOSTREAM_EUSART_EUART_DEBUG_RESTRICT_ENERGY_MODE_TO_ALLOW_RECEPTION    1/SL_IOSTREAM_EUSART_EUART_DEBUG_RESTRICT_ENERGY_MODE_TO_ALLOW_RECEPTION    0/' config/sl_iostream_eusart_euart_debug_config.h
fi

env C_DEFS="-DGIT_COMMIT_ID=\\\"${GIT_VERSION#tags/releases/}\\\" ${BG_EXTRA_DEFS}" make -f BG22Badge.Makefile -j8
retVal=$?
if [ $retVal -ne 0 ]; then
    echo "Error building firmware"
    exit $retVal
else
    echo "Built firmware ${GIT_VERSION#tags/releases/}"
fi

cd ..
cp out/build/debug/BG22Badge.s37 ${BG_OUT:-firmware.s37}
